// Builds web/emb.js: one embedding vector per library concept, used for semantic search in the Ask tab.
// Run after deploying the gateway (it needs the Workers AI binding):
//   node tools/embed-concepts.mjs https://datakul-gateway.<you>.workers.dev
// Then add <script src="emb.js"></script> before app.js in web/index.html. Rerun whenever library.js changes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const gw = (process.argv[2] || "").replace(/\/+$/, "");
if (!gw) { console.error("Usage: node tools/embed-concepts.mjs <gateway address>"); process.exit(1); }

const src = fs.readFileSync(path.join(root, "web/library.js"), "utf8").replace(/^const /gm, "var ");
const { C } = new Function(src + "; return { C };")();
const text = (c) => `${c.title}. ${c.s} ${c.kw}`;

const vecs = {};
let model = "";
for (let i = 0; i < C.length; i += 32) {
  const batch = C.slice(i, i + 32);
  const r = await fetch(gw + "/api/embed", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ texts: batch.map(text) }) });
  if (!r.ok) { console.error("Embedding failed:", r.status, await r.text()); process.exit(1); }
  const j = await r.json();
  model = j.model;
  batch.forEach((c, k) => (vecs[c.id] = j.vectors[k].map((x) => Math.round(x * 1e4) / 1e4)));
  console.log(`embedded ${Math.min(i + 32, C.length)} of ${C.length}`);
}
fs.writeFileSync(path.join(root, "web/emb.js"), `/* Generated by tools/embed-concepts.mjs with ${model}. Do not edit. */\nwindow.DATAKUL_EMB = ${JSON.stringify({ model, vecs })};\n`);
console.log("wrote web/emb.js");
