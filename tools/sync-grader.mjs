// Copies the app's answer checker (web/app.js) into the gateway (worker/src/grader.js),
// so community drafts are checked with exactly the grader learners will be scored by.
// Run after changing the grader in app.js:  node tools/sync-grader.mjs
// Add --check to fail (exit 1) when the copy is out of date instead of writing it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const app = readFileSync(join(root, "web/app.js"), "utf8");
const a = app.indexOf("/* ---- answer checker"), b = app.indexOf("const MIN_WORDS");
if (a < 0 || b < 0) throw new Error("Couldn't find the answer checker in web/app.js");
const out = `// GENERATED by tools/sync-grader.mjs from web/app.js. Do not edit by hand.\n${app.slice(a, b).trim()}\nexport { gNorm, gStem, kwHits, grade };\n`;
const file = join(root, "worker/src/grader.js");
if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(file, "utf8"); } catch {}
  if (cur !== out) { console.error("worker/src/grader.js is out of date. Run: node tools/sync-grader.mjs"); process.exit(1); }
  console.log("grader in sync");
} else {
  writeFileSync(file, out);
  console.log("wrote worker/src/grader.js");
}
